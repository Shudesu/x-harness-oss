import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
export const root = fileURLToPath(new URL('../', import.meta.url));
export function versionArtifacts(version) {
  if (!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version) || version === '0.0.0') throw new Error('Use a nonzero stable SemVer version (e.g. 0.6.1)');
  const files = {};
  for (const name of ['package.json', 'apps/web/package.json', 'apps/worker/package.json']) {
    const pkg = JSON.parse(readFileSync(resolve(root, name), 'utf8')); pkg.version = version;
    files[name] = JSON.stringify(pkg, null, 2) + '\n';
  }
  files['packages/shared/src/version.ts'] = `// Generated by pnpm release:prepare; package.json is the source of truth.\nexport const APP_VERSION = '${version}';\n`;
  files['apps/web/public/version.json'] = JSON.stringify({ version, releaseUrl: `https://github.com/Shudesu/x-harness-oss/releases/tag/v${version}` }, null, 2) + '\n';
  return files;
}
export function checkVersion(version, tag) {
  if (tag && tag !== `v${version}`) throw new Error(`Tag ${tag} differs from v${version}`);
  for (const [name, expected] of Object.entries(versionArtifacts(version))) {
    if (!existsSync(resolve(root, name)) || readFileSync(resolve(root, name), 'utf8') !== expected) throw new Error(`Version metadata is stale: ${name}; run pnpm release:prepare ${version}`);
  }
  const notes = resolve(root, `docs/releases/v${version}.md`);
  if (!existsSync(notes) || !readFileSync(notes,'utf8').startsWith(`# v${version} — `)) throw new Error('Matching release notes are required');
  if (!readFileSync(resolve(root,'CHANGELOG.md'),'utf8').includes(`## [${version}] - `)) throw new Error('Matching CHANGELOG entry is required');
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const version = process.argv[2];
  const current = JSON.parse(readFileSync(resolve(root,'package.json'),'utf8')).version;
  const before=current.split('.').map(Number),after=String(version).split('.').map(Number);
  const difference=after.findIndex((n,i)=>n!==before[i]);
  if(difference>=0 && after[difference]<before[difference])throw new Error('Release version cannot go backwards');
  for (const [name, text] of Object.entries(versionArtifacts(version))) writeFileSync(resolve(root, name), text);
  console.log(`Prepared v${version}. Update CHANGELOG.md and docs/releases/v${version}.md, then run pnpm release:check.`);
}
